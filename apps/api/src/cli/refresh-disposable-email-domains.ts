/**
 * Refreshes the vendored list of temporary-inbox domains that joining the waitlist refuses (D-056):
 *
 *   cd apps/api && bun run waitlist:refresh-disposable-domains
 *
 * The list is disposable-email-domains (CC0), github.com/disposable-email-domains/disposable-email-domains.
 * It rewrites src/lib/waitlist/disposable-email-domain-list.ts; review the diff, then redeploy.
 */
const DISPOSABLE_EMAIL_DOMAIN_LIST_URL =
  'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf'
const OUTPUT_FILE_URL = new URL('../lib/waitlist/disposable-email-domain-list.ts', import.meta.url)
const DOMAIN_PATTERN = /^[a-z0-9.-]+$/
// The list has about 10,000 domains; far fewer means the download went wrong.
const MINIMUM_EXPECTED_DOMAIN_COUNT = 1000

const response = await fetch(DISPOSABLE_EMAIL_DOMAIN_LIST_URL)
if (!response.ok) throw new Error(`The list answered ${response.status}`)
const domains = (await response.text())
  .split('\n')
  .map((line) => line.trim().toLowerCase())
  .filter((line) => line !== '' && !line.startsWith('#'))
const invalidDomains = domains.filter((domain) => !DOMAIN_PATTERN.test(domain))
if (invalidDomains.length > 0) {
  throw new Error(`Unexpected lines in the list: ${invalidDomains.slice(0, 5).join(', ')}`)
}
if (domains.length < MINIMUM_EXPECTED_DOMAIN_COUNT) {
  throw new Error(`Only ${domains.length} domains: the download looks wrong`)
}
const sortedDomains = [...new Set(domains)].sort()

const fileText = `// Generated by \`bun run waitlist:refresh-disposable-domains\` (src/cli/refresh-disposable-email-domains.ts).
// Don't edit by hand. Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0),
// fetched ${new Date().toISOString().slice(0, 10)}: ${sortedDomains.length} temporary-inbox domains (D-056).

/** One domain per line, lowercase. */
export const DISPOSABLE_EMAIL_DOMAIN_LIST_TEXT = \`
${sortedDomains.join('\n')}
\`
`
await Bun.write(OUTPUT_FILE_URL, fileText)
process.stdout.write(`Wrote ${sortedDomains.length} domains to ${OUTPUT_FILE_URL.pathname}\n`)
