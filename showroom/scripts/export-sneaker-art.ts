import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// `bun run export-art`: copies the website's laced Sneakers and its design table into the
// showroom (brief §7.4). The showroom reads the website's files only here, so it builds on its own.
// Both copies are generated: never edit them by hand. Re-run after `bun run website:export-pass-art`.

const showroomRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const websiteRoot = join(showroomRoot, '..', 'website')

const websiteLacedArtDirectory = join(websiteRoot, 'public', 'pass-art', 'laced')
const websiteDesignTablePath = join(websiteRoot, 'src', 'content', 'founding-pass-designs.ts')
export const showroomLacedArtDirectory = join(showroomRoot, 'public', 'sneakers', 'laced')
const showroomDesignTablePath = join(showroomRoot, 'src', 'content', 'sneaker-designs.ts')

const EXPECTED_DESIGN_COUNT = 1000
const WEBSITE_TYPE_IMPORT =
  "import type { PassDesignTables } from '@/lib/founding-pass/pass-design'"
const SHOWROOM_TYPE_IMPORT = "import type { PassDesignTables } from '@/lib/sneaker-design'"

const lacedArtReadme = `# Generated: never edit by hand

The 1,000 laced Sneakers, copied from \`website/public/pass-art/laced/\` by
\`bun run export-art\` (\`scripts/export-sneaker-art.ts\`). They are the frozen Founding Pass art
(\`DESIGNS_FROZEN_ON\`, 2026-10-08), drawn by \`FoundingPassArtRenderer\`. The showroom rasterises
them in the browser and shows them flat: never redrawn, recoloured or tinted.
`

async function exportSneakerArt(): Promise<void> {
  const svgFileNames = (await readdir(websiteLacedArtDirectory))
    .filter((fileName) => fileName.endsWith('.svg'))
    .sort()
  if (svgFileNames.length !== EXPECTED_DESIGN_COUNT) {
    throw new Error(
      `Expected ${EXPECTED_DESIGN_COUNT} laced SVGs in the website, found ${svgFileNames.length}. Run \`bun run website:export-pass-art\` from the repo root first.`,
    )
  }
  await rm(showroomLacedArtDirectory, { recursive: true, force: true })
  await mkdir(showroomLacedArtDirectory, { recursive: true })
  await Promise.all(
    svgFileNames.map((fileName) =>
      copyFile(join(websiteLacedArtDirectory, fileName), join(showroomLacedArtDirectory, fileName)),
    ),
  )
  await writeFile(join(showroomLacedArtDirectory, 'README.md'), lacedArtReadme)

  await writeFile(
    showroomDesignTablePath,
    toShowroomDesignTable(await readFile(websiteDesignTablePath, 'utf8')),
  )
  console.log(`Copied ${svgFileNames.length} laced Sneakers and the design table.`)
}

/** The website's table with the showroom's header and type import. */
function toShowroomDesignTable(websiteSource: string): string {
  if (!websiteSource.includes(WEBSITE_TYPE_IMPORT)) {
    throw new Error(
      "The website's design table changed its type import: update export-sneaker-art.ts",
    )
  }
  const tableStart = websiteSource.indexOf('export const passDesignTables')
  if (tableStart === -1) throw new Error("The website's design table has no passDesignTables")
  return [
    '// GENERATED by `bun run export-art` (showroom/scripts/export-sneaker-art.ts) from',
    '// website/src/content/founding-pass-designs.ts, itself generated from the design table frozen on',
    '// 2026-10-08. Do not edit.',
    SHOWROOM_TYPE_IMPORT,
    '',
    websiteSource.slice(tableStart),
  ].join('\n')
}

if (import.meta.main) await exportSneakerArt()
